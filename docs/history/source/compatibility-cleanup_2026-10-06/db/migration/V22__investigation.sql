CREATE TABLE agent_investigation_run (
  id VARCHAR(64) NOT NULL COMMENT '服务端生成的调查运行标识',
  tenant_id VARCHAR(64) NOT NULL COMMENT '数据所属租户，与当前创建人身份一致',
  actor_id VARCHAR(64) NOT NULL COMMENT '发起调查的账号标识，结合租户定位',
  plan_id VARCHAR(64) NOT NULL COMMENT '关联 dispatch_plan.id，本次唯一目标清单',
  plan_owner_id VARCHAR(64) NOT NULL COMMENT '清单原操作者，由服务端读取，用于受控代核对',
  idempotency_key VARCHAR(128) NOT NULL COMMENT '创建请求稳定键，同用户同键只能对应相同规范化负载',
  payload_hash CHAR(64) NOT NULL COMMENT '规范化提交负载 SHA-256，不含凭据',
  request_json JSON NOT NULL COMMENT '当前请求结构：用户问题、目标条目 ID；问题为脱敏后的允许内容',
  scope_hash CHAR(64) NOT NULL COMMENT '有序目标条目集合和清单身份的摘要',
  active_key CHAR(64) NULL COMMENT '在途时为租户、创建人、清单的摘要；终态为空，释放在途唯一约束',
  expected_execution_version BIGINT NOT NULL COMMENT '提交时绑定的清单执行轮次，禁止借用后来版本',
  source_fingerprint CHAR(64) NULL COMMENT '已冻结本地事实摘要；尚未取得快照时为空',
  snapshot_json JSON NULL COMMENT '当前格式的条目、规则、事件和范围快照；排队阶段为空',
  status VARCHAR(24) NOT NULL DEFAULT 'QUEUED' COMMENT '调查任务状态：QUEUED排队、RUNNING运行、COMPLETED完成、PARTIAL部分完成、FAILED失败、CANCELLED取消、INTERRUPTED中断',
  stop_reason VARCHAR(40) NULL COMMENT '结束原因编码；运行中未结束时为空',
  claim_token VARCHAR(64) NULL COMMENT '当前工作线程认领令牌；未认领或终态为空',
  row_version BIGINT NOT NULL DEFAULT 0 COMMENT '条件更新版本，成功更新后递增',
  lease_until DATETIME(3) NULL COMMENT '当前执行租约 UTC 截止时间，未认领或终态为空',
  queue_expires_at DATETIME(3) NOT NULL COMMENT '排队准入有效期 UTC 截止时间',
  deadline_at DATETIME(3) NULL COMMENT '执行总预算 UTC 截止时间；未开始为空',
  model_name VARCHAR(128) NOT NULL COMMENT '本次实际选定模型标识，不保证供应商持续可用',
  config_json JSON NOT NULL COMMENT '非敏感端点标识、模型参数、预算、工具契约与提示词哈希；不含密钥',
  model_calls INT NOT NULL DEFAULT 0 COMMENT '已尝试模型请求次数，含失败及报告修复',
  tool_calls INT NOT NULL DEFAULT 0 COMMENT '已处理模型工具请求数，含参数错误与结果复用',
  mcp_calls INT NOT NULL DEFAULT 0 COMMENT '已尝试远端 MCP 工具调用次数，批量逐项计数',
  usage_json JSON NULL COMMENT '输入/输出/缓存 token、完整性、费用及币种；缺失用量为 null',
  report_json JSON NULL COMMENT '已通过校验的当前报告结构；尚无合法报告时为空',
  message VARCHAR(512) NULL COMMENT '可展示的状态或失败摘要，不含秘密和原始异常响应',
  created_at DATETIME(3) NOT NULL COMMENT '创建时间，UTC',
  started_at DATETIME(3) NULL COMMENT '首次认领执行时间，尚未开始为空',
  finished_at DATETIME(3) NULL COMMENT '任务终止时间，尚未结束为空',
  updated_at DATETIME(3) NOT NULL COMMENT '最后一次持久状态变更时间，UTC',
  PRIMARY KEY (id),
  UNIQUE KEY uk_run_tenant (tenant_id,id),
  UNIQUE KEY uk_run_key (tenant_id,actor_id,idempotency_key),
  UNIQUE KEY uk_run_active (active_key),
  KEY ix_run_queue (status,queue_expires_at,created_at),
  KEY ix_run_owner (tenant_id,actor_id,plan_id,created_at),
  KEY ix_run_lease (status,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='按租户和创建人归属的异常调查任务；保存绑定清单、当前执行快照、运行状态、预算与报告，终态按保留策略清理，不承载派单执行授权。';

CREATE TABLE agent_investigation_step (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '步骤记录标识，JSON 使用字符串',
  run_id VARCHAR(64) NOT NULL COMMENT '关联调查运行',
  tenant_id VARCHAR(64) NOT NULL COMMENT '冗余所属租户，查询仍强制限定',
  seq INT NOT NULL COMMENT '运行内单调递增序号，用于页面增量读取',
  kind VARCHAR(24) NOT NULL COMMENT 'MODEL、TOOL、VALIDATION、CONTROL',
  status VARCHAR(24) NOT NULL COMMENT 'STARTED、SUCCEEDED、FAILED、SKIPPED',
  tool_call_id VARCHAR(128) NULL COMMENT '原模型工具调用标识，非工具步骤为空',
  tool_name VARCHAR(80) NULL COMMENT '白名单工具名，非工具步骤为空',
  arguments_json JSON NULL COMMENT '脱敏且有界的模型参数，无参数时为空',
  result_json JSON NULL COMMENT '有界结果概要、完整性和证据引用；不复制全部原始记录',
  error_code VARCHAR(64) NULL COMMENT '受控失败类别；成功时为空',
  usage_json JSON NULL COMMENT '本次模型用量及缺失标识，其他步骤为空',
  duration_ms BIGINT NULL COMMENT '单调时钟计算的耗时，单位毫秒；未结束为空',
  started_at DATETIME(3) NOT NULL COMMENT '步骤开始 UTC 时间',
  finished_at DATETIME(3) NULL COMMENT '步骤结束 UTC 时间；执行中为空',
  PRIMARY KEY (id),
  UNIQUE KEY uk_step_seq (run_id,seq),
  KEY ix_step_tenant (tenant_id,run_id,seq),
  CONSTRAINT fk_step_run FOREIGN KEY (tenant_id,run_id) REFERENCES agent_investigation_run(tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='调查运行的可观察步骤，按所属运行继承租户和用户范围；保存模型调用、工具请求、预算及校验结果，不保存模型内部思考，随运行清理。';

CREATE TABLE agent_investigation_evidence (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '证据记录标识，JSON 使用字符串',
  run_id VARCHAR(64) NOT NULL COMMENT '所属调查运行',
  tenant_id VARCHAR(64) NOT NULL COMMENT '所属租户',
  evidence_ref VARCHAR(32) NOT NULL COMMENT '运行内引用，如 E1；模型只使用该引用',
  source_type VARCHAR(32) NOT NULL COMMENT '第 7 节证据来源枚举',
  item_refs_json JSON NOT NULL COMMENT '证据适用的条目引用数组；清单整体证据使用空数组',
  source_ref_json JSON NOT NULL COMMENT '服务端来源定位信息，含清单版本、条目/事件标识；敏感内部字段不默认下发',
  content_json JSON NOT NULL COMMENT '用于验证和展示的脱敏事实，结构随来源类型固定',
  content_hash CHAR(64) NOT NULL COMMENT '规范化证据内容 SHA-256，用于一致性检查，不代替语义正确性',
  observed_at DATETIME(3) NOT NULL COMMENT '事实的观察时间，UTC；远端查询以实际返回时点记录',
  truncated BOOLEAN NOT NULL DEFAULT FALSE COMMENT '是否仅覆盖部分来源内容；true 时不能宣称完整证据',
  created_at DATETIME(3) NOT NULL COMMENT '证据持久化 UTC 时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_evidence_ref (run_id,evidence_ref),
  KEY ix_evidence_tenant (tenant_id,run_id),
  CONSTRAINT fk_evidence_run FOREIGN KEY (tenant_id,run_id) REFERENCES agent_investigation_run(tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='调查报告可引用的脱敏事实快照，绑定运行和条目，记录来源及时点；只供查询和报告校验，随所属运行清理。';

CREATE TABLE agent_investigation_queue (
  tenant_id VARCHAR(64) NOT NULL COMMENT '对应租户的队列互斥标识，插入后通过行锁串行检查准入',
  PRIMARY KEY (tenant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='调查任务按租户进行事务准入的互斥行；不存业务结果，限制并发提交绕过在途配额，随专用 Demo 基线创建。';
